function tokenBlock(definition, extracted) {
  const { tokens } = extracted;
  return `export const tokens = {
  spacing: ${JSON.stringify(tokens.spacing)} as const,
  radius: ${JSON.stringify(tokens.radius)} as const,
  density: ${JSON.stringify(tokens.density)} as const,
  primary: ${JSON.stringify(tokens.primary)},
  typeScale: { display: 56, heading: 32, body: 16, mono: 13 },
  surface: ${JSON.stringify(definition.slug)},
} as const;
`;
}

